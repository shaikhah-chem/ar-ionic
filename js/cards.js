/* تحويل الترميز البسيط إلى HTML:  Mg^{2+} → Mg<sup>2+</sup>
   ويُعزل كل رمز كيميائي باتجاه يسار→يمين حتى لا تنقلب الشحنات داخل الجملة العربية */
const sup = (m) => m.replace(/\^\{([^}]*)\}/g, '<sup>$1</sup>').replace(/_\{([^}]*)\}/g, '<sub>$1</sub>');
export function chemHTML(s) {
  if (!/[؀-ۿ]/.test(s)) return `<bdi dir="ltr" class="chem">${sup(s)}</bdi>`; // سطر رياضي/كيميائي كامل
  return s
    .replace(/[0-9]*[A-Z][A-Za-z()0-9]*(?:(?:\^|_)\{[^}]*\}[A-Za-z()0-9]*)*/g, (m) => `<bdi dir="ltr" class="chem">${sup(m)}</bdi>`)
    .replace(/(^|[\s(])([+−]\d+)(?=[\s).،]|$)/g, '$1<bdi dir="ltr" class="chem">$2</bdi>'); // أعداد بإشارة مثل +6 و −6
}
